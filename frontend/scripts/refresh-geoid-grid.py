#!/usr/bin/env python3
"""Refresh the bounded NGS geoid grids used for Denver height alignment.

The runtime never calls the NGS service.  This maintainer-only command makes a
small, sequential set of requests and writes an atomic TypeScript data module
plus a provenance manifest.
"""

from __future__ import annotations

import hashlib
import json
import time
import urllib.parse
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src" / "cesium" / "geoid-grid.ts"
MANIFEST = ROOT / "public" / "terrain" / "geoid-grid-manifest.json"
ENDPOINT = "https://geodesy.noaa.gov/api/geoid/ght"
BOUNDS = (-105.8, 39.4, -104.4, 40.1)
STEP = 0.1
MODELS = {"geoid12a": 12, "geoid18": 14}


def coordinates(start: float, stop: float) -> list[float]:
    count = round((stop - start) / STEP)
    return [round(start + index * STEP, 10) for index in range(count + 1)]


def fetch_height(latitude: float, longitude: float, model: int) -> tuple[float, float]:
    query = urllib.parse.urlencode(
        {"lat": latitude, "lon": longitude, "model": model, "units": "m"}
    )
    request = urllib.request.Request(
        f"{ENDPOINT}?{query}",
        headers={"User-Agent": "SkybyDay/0.1 geoid-grid-refresh"},
    )
    last_error: Exception | None = None
    for attempt in range(3):
        try:
            with urllib.request.urlopen(request, timeout=10) as response:
                if int(response.headers.get("Content-Length", "0")) > 16_384:
                    raise ValueError("NGS response is unexpectedly large")
                payload = json.load(response)
            if payload.get("geoidModel") not in {"GEOID12A", "GEOID18"}:
                raise ValueError(f"unexpected geoid model: {payload!r}")
            height = float(payload["geoidHeight"])
            error = float(payload["error"])
            if not (-100.0 < height < 100.0 and 0.0 <= error < 10.0):
                raise ValueError(f"invalid NGS values: {payload!r}")
            return height, error
        except (OSError, ValueError, KeyError, json.JSONDecodeError) as error:
            last_error = error
            if attempt == 2:
                break
            time.sleep(1.0 * (attempt + 1))
    raise RuntimeError(f"NGS request failed: {last_error}")


def main() -> None:
    west, south, east, north = BOUNDS
    longitudes = coordinates(west, east)
    latitudes = coordinates(south, north)
    grids: dict[str, list[float]] = {}
    errors: dict[str, list[float]] = {}
    for name, model in MODELS.items():
        values: list[float] = []
        model_errors: list[float] = []
        for latitude in latitudes:
            for longitude in longitudes:
                height, error = fetch_height(latitude, longitude, model)
                values.append(height)
                model_errors.append(error)
                time.sleep(0.1)
        grids[name] = values
        errors[name] = model_errors

    generated = datetime.now(UTC).replace(microsecond=0).isoformat()
    rows = len(latitudes)
    columns = len(longitudes)
    arrays = []
    for name in MODELS:
        values = ", ".join(f"{value:.3f}" for value in grids[name])
        arrays.append(
            f"export const {name.upper()}_UNDULATION_M = new Float32Array([{values}]);"
        )
    source = (
        "// Generated by scripts/refresh-geoid-grid.py; do not hand edit.\n"
        "// biome-ignore-all format: generated data snapshot\n"
        f"export const GEOID_GRID_WEST = {west};\n"
        f"export const GEOID_GRID_SOUTH = {south};\n"
        f"export const GEOID_GRID_STEP = {STEP};\n"
        f"export const GEOID_GRID_COLUMNS = {columns};\n"
        f"export const GEOID_GRID_ROWS = {rows};\n"
        + "\n".join(arrays)
        + "\n"
    )
    digest = hashlib.sha256(source.encode()).hexdigest()
    manifest = {
        "generated_at": generated,
        "source": ENDPOINT,
        "source_documentation": "https://geodesy.noaa.gov/web_services/geoid.shtml",
        "models": MODELS,
        "bounds_degrees": [west, south, east, north],
        "spacing_degrees": STEP,
        "columns": columns,
        "rows": rows,
        "request_count": rows * columns * len(MODELS),
        "units": "metres",
        "height_relation": "h_NAD83(2011) = H_NAVD88 + N_geoid",
        "maximum_service_error_m": {
            name: max(model_errors) for name, model_errors in errors.items()
        },
        "typescript_sha256": digest,
        "limitations": [
            "Bilinear interpolation adds unquantified error between 0.1-degree samples.",
            "GEOID18 is defined for NAD83(2011), not WGS84; no frame/epoch transform is applied.",
            "GEOID12A is retained only for sources explicitly tagged with that superseded model.",
        ],
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    output_tmp = OUTPUT.with_suffix(".tmp")
    manifest_tmp = MANIFEST.with_suffix(".tmp")
    output_tmp.write_text(source)
    manifest_tmp.write_text(json.dumps(manifest, indent=2) + "\n")
    output_tmp.replace(OUTPUT)
    manifest_tmp.replace(MANIFEST)


if __name__ == "__main__":
    main()
